import { NextRequest } from "next/server";
import { handler, ApiError } from "@/lib/api";
import { getDB } from "@/lib/db";
import { getCurrentUser } from "@/lib/auth";
import { buildPdf } from "@/lib/pdf";

/**
 * GET /api/download?type=syllabus|material&id=…&format=txt|pdf
 *
 * Generates a real, downloadable document. In demo mode the content is built
 * from the seeded academic records and clearly labelled as sample data.
 */
export const GET = handler(async (req: NextRequest) => {
  const url = new URL(req.url);
  const type = url.searchParams.get("type");
  const id = url.searchParams.get("id") ?? "";
  const format = url.searchParams.get("format") ?? "pdf";

  const viewer = await getCurrentUser();
  if (!viewer) throw new ApiError(401, "Sign in to download academic resources.");

  const db = getDB();
  let filename = "campusconnect-document";
  let text = "";
  let blocks: { text: string; size: number; gap: number }[] = [];

  if (type === "syllabus") {
    const s = db.syllabus.find((x) => x.id === id);
    if (!s) throw new ApiError(404, "Syllabus not found.");
    filename = `${s.code}-${s.subject.replace(/\s+/g, "-")}`;
    blocks = [
      { text: s.subject.toUpperCase(), size: 18, gap: 30 },
      { text: `${s.code}  ·  ${s.department}  ·  ${s.semester}  ·  ${s.credits} credits`, size: 11, gap: 24 },
      { text: "Demo document generated by CampusConnect - sample data, not an official college record.", size: 9, gap: 30 },
      ...s.units.flatMap((u) => [
        { text: u.title, size: 13, gap: 20 },
        ...u.topics.map((t) => ({ text: `   - ${t}`, size: 11, gap: 16 })),
        { text: "", size: 11, gap: 14 },
      ]),
      { text: `Updated: ${s.updatedAt.slice(0, 10)}`, size: 10, gap: 16 },
    ];
    text = [s.subject, `${s.code} · ${s.department} · ${s.semester}`, "", ...s.units.flatMap((u) => [u.title, ...u.topics.map((t) => `  - ${t}`), ""])].join("\n");
  } else if (type === "material") {
    const m = db.materials.find((x) => x.id === id);
    if (!m) throw new ApiError(404, "Material not found.");
    filename = m.title.replace(/\s+/g, "-").slice(0, 48);
    blocks = [
      { text: m.title.toUpperCase(), size: 17, gap: 30 },
      { text: `${m.type} · ${m.subject} · ${m.department} · ${m.semester}`, size: 11, gap: 24 },
      { text: "Demo document generated by CampusConnect - sample data, not an official college record.", size: 9, gap: 28 },
      { text: "Contents", size: 13, gap: 20 },
      { text: "This placeholder stands in for the uploaded file. In production, faculty", size: 11, gap: 16 },
      { text: "upload the real PDF through the admin dashboard and it is stored in the", size: 11, gap: 16 },
      { text: "file storage service, served through the same access-controlled route.", size: 11, gap: 16 },
      { text: "", size: 11, gap: 14 },
      { text: `Uploaded: ${m.createdAt.slice(0, 10)} · ${m.downloads} downloads so far`, size: 10, gap: 16 },
    ];
    text = `${m.title}\n${m.type} · ${m.subject} · ${m.department} · ${m.semester}\n\nDemo document generated by CampusConnect - sample data.`;
  } else {
    throw new ApiError(400, "Unknown document type.");
  }

  if (format === "txt") {
    return new Response(text, {
      headers: {
        "Content-Type": "text/plain; charset=utf-8",
        "Content-Disposition": `attachment; filename="${filename}.txt"`,
      },
    });
  }

  const pdf = buildPdf(filename, blocks);
  return new Response(new Uint8Array(pdf), {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Length": String(pdf.length),
      "Content-Disposition": `attachment; filename="${filename}.pdf"`,
    },
  });
});
